#!/usr/bin/env node
// Build-time script: generates curriculumBundle.js for the Worker pipeline.
// Reads all knowledge .md files, agent configs, prompts, and dispatch table,
// then writes them as string constants in a single JS module.
//
// Usage: node api/scripts/build-curriculum.mjs
// Must be run from project root before wrangler deploy.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join, resolve } from 'path';

const ROOT = resolve(import.meta.dirname, '../..');
const OUT = join(ROOT, 'api/src/pipeline/curriculumBundle.js');

// ─── Curriculum files (same 17 as knowledgeBundle.js) ────────

const CURRICULUM_FILES = [
  'knowledge/research-references/advanced-financial-analysis.md',
  'knowledge/research-references/buffett-writing-style-guide.md',
  'knowledge/research-references/capex-cash-flow-explained.md',
  'knowledge/research-references/equity-bond-research.md',
  'knowledge/research-references/fgr.md',
  'knowledge/research-references/guru-list.md',
  'knowledge/research-references/rule-1-workflow.md',
  'knowledge/research-references/rule-one-fundamentals.md',
  'knowledge/research-references/tools-for-analysis.md',
  'knowledge/stage-1-one-pager/one-pager.md',
  'knowledge/stage-1-one-pager/template.md',
  'knowledge/stage-2-pitch-deck/pitch-deck-I.md',
  'knowledge/stage-2-pitch-deck/pitch-deck-II.md',
  'knowledge/stage-2-pitch-deck/pitch-deck-III.md',
  'knowledge/stage-2-pitch-deck/pitch-deck-IV.md',
  'knowledge/stage-3-full-story/story-form-I.md',
  'knowledge/stage-3-full-story/story-form-II.md',
];

// ─── Agent directories ──────────────────────────────────────

const AGENTS_DIR = join(ROOT, 'agents');
const AGENT_DIRS = readdirSync(AGENTS_DIR, { withFileTypes: true })
  .filter(d => d.isDirectory() && d.name !== 'orchestrator' && d.name !== 'writing-briefs' && d.name !== '__tests__')
  .map(d => d.name)
  .sort();

// ─── Read files ─────────────────────────────────────────────

function readFile(path) {
  const full = join(ROOT, path);
  if (!existsSync(full)) {
    console.warn(`  WARN: Missing file: ${path}`);
    return '';
  }
  return readFileSync(full, 'utf8');
}

function escapeForTemplate(str) {
  // Escape backticks and ${} for template literals
  return str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

// ─── Generate ───────────────────────────────────────────────

let output = `// AUTO-GENERATED by api/scripts/build-curriculum.mjs
// Do not edit directly. Regenerate with: node api/scripts/build-curriculum.mjs
// Generated: ${new Date().toISOString()}
\n`;

// Curriculum map
output += '// ─── Curriculum Content ────────────────────────────────────\n\n';
output += 'export const CURRICULUM_MAP = {\n';
for (const path of CURRICULUM_FILES) {
  const content = readFile(path);
  console.log(`  curriculum: ${path} (${content.length} chars)`);
  output += `  '${path}': \`${escapeForTemplate(content)}\`,\n`;
}
output += '};\n\n';

// Agent configs
output += '// ─── Agent Configs ────────────────────────────────────────\n\n';
output += 'export const AGENT_CONFIGS = {\n';
for (const agent of AGENT_DIRS) {
  const configPath = join('agents', agent, 'config.json');
  const content = readFile(configPath);
  if (content) {
    console.log(`  config: ${configPath}`);
    output += `  '${agent}': ${content.trim()},\n`;
  }
}
output += '};\n\n';

// Agent prompts (base + fullStory overlays)
output += '// ─── Agent Prompts ────────────────────────────────────────\n\n';
output += 'export const AGENT_PROMPTS = {\n';
for (const agent of AGENT_DIRS) {
  const basePath = join('agents', agent, 'prompt.md');
  const base = readFile(basePath);
  const fullStoryPath = join('agents', agent, 'prompts', 'fullStory.md');
  const fullStory = existsSync(join(ROOT, fullStoryPath)) ? readFile(fullStoryPath) : null;

  if (base) {
    console.log(`  prompt: ${agent} (base: ${base.length}${fullStory ? `, fullStory: ${fullStory.length}` : ''})`);
    output += `  '${agent}': {\n`;
    output += `    base: \`${escapeForTemplate(base)}\`,\n`;
    if (fullStory) {
      output += `    fullStory: \`${escapeForTemplate(fullStory)}\`,\n`;
    }
    output += `  },\n`;
  }
}
output += '};\n\n';

// Dispatch table
output += '// ─── Dispatch Table ───────────────────────────────────────\n\n';
const dispatchPath = join('agents', 'orchestrator', 'dispatch-table.json');
const dispatchContent = readFile(dispatchPath);
console.log(`  dispatch: ${dispatchPath} (${dispatchContent.length} chars)`);
output += `export const DISPATCH_TABLE = ${dispatchContent.trim()};\n\n`;

// Named exports for One-Pager Generator compatibility
output += '// ─── Named Exports (One-Pager Generator compat) ──────────\n\n';
output += `export const onePagerCurriculum = CURRICULUM_MAP['knowledge/stage-1-one-pager/one-pager.md'];\n`;
output += `export const onePagerTemplate = CURRICULUM_MAP['knowledge/stage-1-one-pager/template.md'];\n`;
output += `export const buffettWritingStyleGuide = CURRICULUM_MAP['knowledge/research-references/buffett-writing-style-guide.md'];\n`;

// Write output
writeFileSync(OUT, output, 'utf8');
const sizeKB = Math.round(output.length / 1024);
console.log(`\nGenerated: ${OUT} (${sizeKB} KB)`);
